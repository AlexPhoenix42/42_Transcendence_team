#!/bin/bash
# Creates the host directories the ELK containers bind-mount, with ownership the
# containers can actually write to. Idempotent, needs no sudo (everything lives
# under $HOME).
#
# Why this exists: Docker creates a missing bind-mount source directory as
# root:root. Elasticsearch runs as uid 1000 and would then fail to write its
# data directory, so the directories have to exist with the right owner *before*
# the first `up`. This mirrors steps 7-8 of up_dep_secure.sh, which do the same
# for the ModSecurity log dir and the restic repo.
#
# Usage: ./ELK/host-setup/prepare-elk-dirs.sh
set -euo pipefail

# Honour the invoking user's HOME even under sudo, same as up_dep_secure.sh.
if [ -n "${SUDO_USER:-}" ]; then
	HOME="$(getent passwd "${SUDO_USER}" | cut -d: -f6)"
	export HOME
fi

# uid:gid the elasticsearch image runs as (uid 1000, gid 0 -- see
# `docker run --rm --entrypoint id elasticsearch:9.5.2`).
ES_UID=1000
ES_GID=1000

ES_DATA="${HOME}/goinfre/trans_data/trans_es_data"
# Deliberately NOT under trans_backups: up_dep_secure.sh runs
# `chown -R 100:100` and `chmod 750` over that whole tree for the restic repo,
# which would take the snapshot directory away from Elasticsearch (uid 1000)
# every time it ran. Keeping ES snapshots in their own directory decouples them.
ES_SNAPSHOTS="${HOME}/goinfre/trans_data/trans_es_snapshots"

for dir in "${ES_DATA}" "${ES_SNAPSHOTS}"; do
	echo "==> ${dir}"
	mkdir -p "${dir}"
	chown "${ES_UID}:${ES_GID}" "${dir}"
	chmod 755 "${dir}"
done

# ── Elasticsearch bootstrap credentials ──────────────────────────────────────
# ES needs the `elastic` superuser password at first boot, before Vault is in
# the picture. Keep it out of the tracked .env by generating a git-ignored file
# that docker-compose reads via `env_file:`. Build step 9 replaces this with the
# Vault AppRole path (secret/data/elasticsearch), at which point this file only
# matters for the dev compose.
ELK_ENV="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)/.env.elk"

if [ -f "${ELK_ENV}" ]; then
	echo "==> ${ELK_ENV} already exists, leaving it alone"
else
	echo "==> Generating ${ELK_ENV}"
	umask 077
	rand() { openssl rand -base64 "$1" | tr -d '/+=' | cut -c1-"$2"; }
	KIBANA_PW="$(rand 24 24)"
	{
		echo "# Generated by ELK/host-setup/prepare-elk-dirs.sh -- do not commit."
		echo "# Variables are named after what each consumer expects, so services can"
		echo "# load this file directly via \`env_file:\` with no name mapping and no"
		echo "# secrets passed through the shell."
		echo
		echo "# Elasticsearch: bootstraps the elastic superuser on first boot."
		echo "# Also read by elk-init to authenticate its setup calls."
		echo "ELASTIC_PASSWORD=$(rand 24 24)"
		echo
		echo "# elk-init: the password it assigns to the built-in kibana_system"
		echo "# account, which ships with none."
		echo "KIBANA_SYSTEM_PASSWORD=${KIBANA_PW}"
		echo
		echo "# Kibana reads these two verbatim to authenticate to Elasticsearch."
		echo "# Same value as KIBANA_SYSTEM_PASSWORD above -- duplicated rather than"
		echo "# mapped so neither service needs shell interpolation of a secret."
		echo "ELASTICSEARCH_USERNAME=kibana_system"
		echo "ELASTICSEARCH_PASSWORD=${KIBANA_PW}"
		echo
		echo "# Kibana encrypts saved objects (incl. the dashboards this module is"
		echo "# graded on) with these. Unpinned, Kibana generates random keys at each"
		echo "# boot and previously saved objects become undecryptable."
		echo "XPACK_ENCRYPTEDSAVEDOBJECTS_ENCRYPTIONKEY=$(rand 48 32)"
		echo "XPACK_REPORTING_ENCRYPTIONKEY=$(rand 48 32)"
		echo "XPACK_SECURITY_ENCRYPTIONKEY=$(rand 48 32)"
		echo
		echo "# Logstash authenticates to ES as a dedicated least-privilege user"
		echo "# (logstash_internal), created by elk-init. It may only write to"
		echo "# logs-* -- ingesting as the elastic superuser would mean a"
		echo "# compromised pipeline could read or delete anything in the cluster."
		echo "LOGSTASH_PASSWORD=$(rand 24 24)"
	} > "${ELK_ENV}"
	chmod 600 "${ELK_ENV}"
	# These scripts run under sudo, so hand the file back to the real user --
	# otherwise it lands root-owned 0600 and no ordinary command can read it.
	if [ -n "${SUDO_USER:-}" ]; then
		chown "${SUDO_USER}:$(id -gn "${SUDO_USER}")" "${ELK_ENV}"
	fi
fi

echo
echo "OK: Elasticsearch data and snapshot directories ready."
ls -ld "${ES_DATA}" "${ES_SNAPSHOTS}"
ls -l "${ELK_ENV}"
